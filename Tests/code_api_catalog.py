#!/usr/bin/env python3
"""Generate the embedded source editor's API name/signature catalogue from ScriptableEntity.h."""
import json
import pathlib
import sys
sys.dont_write_bytecode = True
import docs_check
root = pathlib.Path(__file__).resolve().parent.parent
header = root / "Zamin/src/Zamin/Scripting/ScriptableEntity.h"
lines = header.read_text().splitlines()
entries = []
for name in sorted(docs_check.public_script_functions()):
    import re
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*\(")
    signature = next((line.split("//")[0].strip().split("{")[0].rstrip() for line in lines
                      if line.startswith("        ") and not line.startswith("         ")
                      and not line.lstrip().startswith("//") and pattern.search(line)), name)
    entries.append("{" + json.dumps(name) + ", " + json.dumps(signature) + "},")
text = "// Generated by Tests/code_api_catalog.py; do not edit by hand.\n" + "\n".join(entries) + "\n"
target = root / "Editor/src/CodeAPICatalog.inc"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text:
        raise SystemExit("Code API catalogue is stale; run python3 Tests/code_api_catalog.py")
else:
    target.write_text(text)
print(f"Code API: {len(entries)} functions")
