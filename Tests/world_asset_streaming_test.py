#!/usr/bin/env python3
"""World asset streaming acceptance: real Player runs along a repeatable camera tour (ZAMIN_WORLD_TOUR),
judged from the per-frame report the Player writes (ZAMIN_WORLD_REPORT). No simulated loader or renderer.

  --stage budget     heavy generated world (2048 px textures, 5184-triangle models): the asset budget run
                     against the same world on the pre-budget main-thread path; hard per-frame gates.
  --stage residency  the heavy world under a tracked-GPU limit and under an RSS limit, a two-lap leak
                     check (fast camera, void, return) and a damaged world (missing / corrupt cells and files).
  --stage demo       Projects/WorldGallery3D as committed: generator reproducibility, two identical tours,
                     the editor world panel, export, and the tour again in the relocated export.

The heavy worlds are generated by Tools/make_world_gallery.py into a temporary folder.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MIB = 1024 * 1024
# Main-thread streaming work of one frame (WorldStreaming's update + AsyncLoader's uploads), milliseconds.
# Measured about 13 ms on Mesa llvmpipe with 2 MiB of uploads per frame; the pre-budget path needs 100+.
HARD_STREAM_MS = float(os.environ.get("ZAMIN_WORLD_HARD_MS", "30"))
# A long frame: this much over the run's median frame. None may be caused by streaming work (more than
# STREAM_WORK_MS of it in that frame); the few that remain are the renderer's own first uses (a shader
# variant compiled when a new kind of draw first appears), and the 99th percentile stays within it too.
HARD_FRAME_OVER_MEDIAN_MS = float(os.environ.get("ZAMIN_WORLD_HARD_FRAME_MS", "40"))
STREAM_WORK_MS = 5.0
MAX_RENDERER_ONE_OFF_FRAMES = 5


def long_frames(report):
    """(frames over the median by the limit, how many of them did streaming work)."""
    limit = report["Summary"]["FrameMs"]["P50"] + HARD_FRAME_OVER_MEDIAN_MS
    work = stream_ms(report)
    late = [i for i, value in enumerate(column(report, "FrameMs")) if value > limit]
    return len(late), sum(1 for i in late if work[i] > STREAM_WORK_MS)


class Failure(RuntimeError):
    pass


def check(condition, message):
    if not condition:
        raise Failure(message)


class Runner:
    def __init__(self, build, out, work):
        self.build, self.out, self.work = build, out, work
        self.xvfb = [] if os.environ.get("DISPLAY") else ["xvfb-run", "-a", "-s", "-screen 0 1600x900x24 -nolisten tcp"]
        self.home = work / "home"
        self.home.mkdir(parents=True, exist_ok=True)

    def env(self, **extra):
        env = os.environ.copy()
        env.update(HOME=str(self.home), LIBGL_ALWAYS_SOFTWARE="1", LP_NUM_THREADS="2", ZAMIN_GL_DEBUG="1")
        env.update({key: str(value) for key, value in extra.items()})
        return env

    def generate(self, name, *options):
        project = self.work / name
        shutil.rmtree(project, ignore_errors=True)
        subprocess.run([sys.executable, str(ROOT / "Tools/make_world_gallery.py"), str(project), *options], check=True, stdout=subprocess.DEVNULL)
        return project

    def tour(self, label, project, tour=None, frames=None, command=None, screenshot=False, timeout=900):
        """Runs the Player with the tour; returns the parsed report. The run must exit cleanly and finish the tour."""
        tour = Path(tour) if tour else project / "Assets/Worlds/Gallery.ztour"
        spec = json.loads(tour.read_text())
        total = spec["Warmup"] + spec["Keys"][-1]["Frame"] + 1
        report, log = self.out / f"{label}.json", self.out / f"{label}.log"
        report.unlink(missing_ok=True)
        extra = {"ZAMIN_WORLD_TOUR": tour, "ZAMIN_WORLD_REPORT": report, "ZAMIN_MAX_FRAMES": frames or total + 30}
        if screenshot:
            extra["ZAMIN_SCREENSHOT"] = self.out / f"{label}.png"
        with log.open("w") as stream:
            result = subprocess.run(self.xvfb + (command or [str(self.build / "bin/ZaminPlayer"), str(project)]), env=self.env(**extra),
                                    stdout=stream, stderr=subprocess.STDOUT, timeout=timeout)
        text = log.read_text(errors="replace")
        check(result.returncode == 0, f"{label}: Player exit code {result.returncode}; see {log}")
        check("GL_INVALID_" not in text and "Assertion failed" not in text, f"{label}: graphics / assertion error; see {log}")
        check(report.is_file(), f"{label}: no tour report; see {log}")
        data = json.loads(report.read_text())
        data["Log"] = text
        if frames is None:
            check(data["Complete"] and data["Summary"]["Frames"] == spec["Keys"][-1]["Frame"] + 1, f"{label}: tour did not finish; see {log}")
        if screenshot:
            picture = self.out / f"{label}.png"
            check(picture.is_file() and picture.read_bytes().startswith(b"\x89PNG\r\n\x1a\n"), f"{label}: screenshot missing")
        return data


def column(report, name):
    index = report["Columns"].index(name)
    return [row[index] for row in report["Samples"]]


def stream_ms(report):
    return [a + b for a, b in zip(column(report, "WorldMs"), column(report, "UploadMs"))]


def set_policy(project, **changes):
    file = project / "Assets/Worlds/Main.zworld"
    world = json.loads(file.read_text())
    world["Streaming"].update(changes)
    file.write_text(json.dumps(world, indent=1))
    return world["Streaming"]


def brief(report):
    s, w = report["Summary"], report.get("World", {})
    return {"Frames": s["Frames"], "FrameMsP50": round(s["FrameMs"]["P50"], 2), "FrameMsP95": round(s["FrameMs"]["P95"], 2),
            "FrameMsP99": round(s["FrameMs"]["P99"], 2), "FrameMsMax": round(s["FrameMs"]["Max"], 2),
            "StreamMsMax": round(max(stream_ms(report)), 2), "WorldMsMax": round(s["WorldMs"]["Max"], 2), "UploadMsMax": round(s["UploadMs"]["Max"], 2),
            "PeakUploadBytesPerFrame": s["PeakUploadBytesPerFrame"], "PeakUploadCallsPerFrame": s["PeakUploadCallsPerFrame"],
            "RSSMiB": {"First": s["FirstRSSBytes"] // MIB, "Peak": s["PeakRSSBytes"] // MIB, "Last": s["LastRSSBytes"] // MIB},
            "GPUMiB": {"First": s["FirstRequestedGPUBytes"] // MIB, "Peak": s["PeakRequestedGPUBytes"] // MIB, "Last": s["LastRequestedGPUBytes"] // MIB},
            "PeakActive": s["PeakActive"], "PeakFailed": s["PeakFailed"], "PressureFrames": s["PressureFrames"],
            **{key: w.get(key) for key in ("Activations", "Unloads", "Failed", "MainThreadImageDecodes", "MainThreadModelParses", "FilesStaged",
                                           "FilesUnreadable", "AssetCancellations", "OversizeUploads", "UploadBudgetDeferrals", "StagingBudgetFailures",
                                           "PeakReservedStagedBytes", "PressureEvictions", "ResidencyRefusals", "ResidencyBlocked", "MemoryReleases",
                                           "PeakMemoryReleaseMs", "CacheEvictions")}}


HEAVY = ["--texture-size", "2048", "--model-detail", "3", "--window", "640x360"]


def stage_budget(run):
    budget = run.tour("budget", run.generate("heavy", *HEAVY))
    legacy = run.tour("legacy", run.generate("heavy-legacy", *HEAVY, "--legacy"))
    policy, world, summary = budget["Policy"], budget["World"], budget["Summary"]
    check(policy["AssetStreaming"] and not legacy["Policy"]["AssetStreaming"], "budget: policies")
    check(world["Failed"] == 0 and summary["PeakFailed"] == 0 and world["Activations"] > 0 and summary["PeakActive"] >= 4, f"budget: cells {brief(budget)}")
    # 1. Nothing is decoded or parsed by the main thread; the pre-budget path does both there.
    check(world["MainThreadImageDecodes"] == 0 and world["MainThreadModelParses"] == 0, f"budget: main-thread loads {brief(budget)}")
    check(legacy["World"]["MainThreadImageDecodes"] > 0 and legacy["World"]["MainThreadModelParses"] > 0, "legacy: the counters do not see main-thread loads")
    # 2. Hard per-frame upload budget: bytes and calls of every frame, no unit larger than the budget.
    check(0 < summary["PeakUploadBytesPerFrame"] <= policy["MaxAssetUploadBytesPerFrame"], f"budget: upload bytes per frame {brief(budget)}")
    check(summary["PeakUploadCallsPerFrame"] <= policy["MaxAssetUploadsPerFrame"] and world["OversizeUploads"] == 0, f"budget: upload calls {brief(budget)}")
    check(max(column(budget, "UploadBytes")) == summary["PeakUploadBytesPerFrame"], "budget: summary disagrees with its samples")
    # 3. Hard staging budget: decoded data waiting for the GPU.
    check(world["StagingBudgetFailures"] == 0 and 0 < world["PeakReservedStagedBytes"] <= policy["MaxStagedAssetBytes"], f"budget: staged bytes {brief(budget)}")
    check(max(column(budget, "StagedBytes")) <= policy["MaxStagedAssetBytes"], "budget: staged bytes sample over the limit")
    # 4. Hard frame-time acceptance: main-thread streaming work of every frame, against the pre-budget run too.
    hard, old = max(stream_ms(budget)), max(stream_ms(legacy))
    check(hard <= HARD_STREAM_MS, f"budget: {hard:.2f} ms of streaming work in one frame (limit {HARD_STREAM_MS})")
    check(old > HARD_STREAM_MS and hard <= old / 2, f"budget {hard:.2f} ms against legacy {old:.2f} ms: the gate does not separate them")
    late, streamed = long_frames(budget)
    old_late, old_streamed = long_frames(legacy)
    check(streamed == 0, f"budget: {streamed} frames made {HARD_FRAME_OVER_MEDIAN_MS} ms longer than the median by streaming work")
    check(late <= MAX_RENDERER_ONE_OFF_FRAMES, f"budget: {late} frames over the median by {HARD_FRAME_OVER_MEDIAN_MS} ms")
    check(summary["FrameMs"]["P99"] - summary["FrameMs"]["P50"] <= HARD_FRAME_OVER_MEDIAN_MS, f"budget: p99 frame {summary['FrameMs']['P99']:.1f} ms against a median of {summary['FrameMs']['P50']:.1f}")
    check(old_streamed >= 10, f"legacy: only {old_streamed} long frames with streaming work - the frame gate does not separate the two paths")
    # A cell over the staging budget fails by name; the Player keeps running and uploads nothing.
    strict_project = run.generate("heavy-strict", *HEAVY)
    set_policy(strict_project, MaxAssetBytesPerCell=8 * MIB)
    strict = run.tour("strict", strict_project, frames=420)
    check(strict["Summary"]["PeakFailed"] > 0 and strict["World"]["Activations"] == 0 and strict["World"]["UploadBytes"] == 0, f"strict: {brief(strict)}")
    check(strict["World"]["StagingBudgetFailures"] > 0 and strict["World"]["MainThreadImageDecodes"] == 0, f"strict: {brief(strict)}")
    return {"Budget": brief(budget), "Legacy": brief(legacy), "Strict": brief(strict),
            "HardStreamMsLimit": HARD_STREAM_MS, "HardFrameOverMedianMsLimit": HARD_FRAME_OVER_MEDIAN_MS,
            "BudgetLongFrames": {"All": late, "WithStreamingWork": streamed}, "LegacyLongFrames": {"All": old_late, "WithStreamingWork": old_streamed},
            "BudgetFramesOver10msOfStreaming": sum(1 for v in stream_ms(budget) if v > 10),
            "LegacyFramesOver30msOfStreaming": sum(1 for v in stream_ms(legacy) if v > 30),
            "UploadBudget": {"Bytes": policy["MaxAssetUploadBytesPerFrame"], "Calls": policy["MaxAssetUploadsPerFrame"]}}


def two_laps(tour_file, out):
    spec = json.loads(tour_file.read_text())
    length = spec["Keys"][-1]["Frame"] + 1
    spec["Keys"] += [dict(key, Frame=key["Frame"] + length, Jump=True if key["Frame"] == 0 else key["Jump"]) for key in spec["Keys"]]
    spec["Name"] += " (two laps)"
    out.write_text(json.dumps(spec, indent=1))
    return length


def stage_residency(run):
    project = run.generate("heavy", *HEAVY)
    # ---- reference: two laps of sweep, fast camera, void and return without limits. Nothing may grow lap over lap.
    lap = two_laps(project / "Assets/Worlds/Gallery.ztour", run.work / "two-laps.ztour")
    free = run.tour("unlimited", project, tour=run.work / "two-laps.ztour")
    rss, gpu, active = column(free, "RSSBytes"), column(free, "RequestedGPUBytes"), column(free, "Active")
    check(free["World"]["Failed"] == 0 and free["Summary"]["PeakFailed"] == 0, f"unlimited: failed cells {brief(free)}")
    check(free["World"]["AssetCancellations"] > 0, "unlimited: the fast camera cancelled nothing")
    check(free["World"]["MainThreadImageDecodes"] == 0 and free["World"]["MainThreadModelParses"] == 0 and free["World"]["OversizeUploads"] == 0, f"unlimited: {brief(free)}")
    void = [i for i, row in enumerate(free["Samples"]) if row[free["Columns"].index("CameraX")] > 4000]
    void1, void2 = [i for i in void if i < lap][-1], [i for i in void if i >= lap][-1]
    check(active[void1] == 0 and active[void2] == 0, "unlimited: the void did not unload everything")
    check(active[lap - 1] > 0 and active[-1] > 0 and active[-1] == active[lap - 1], f"unlimited: return {active[lap - 1]} then {active[-1]} active cells")
    check(gpu[void2] <= gpu[void1] + 4 * MIB, f"unlimited: tracked GPU grew between voids {gpu[void1]} -> {gpu[void2]}")
    check(max(gpu[lap:]) <= max(gpu[:lap]) + 48 * MIB, "unlimited: tracked GPU peak grew in the second lap")
    check(rss[void2] <= rss[void1] + 96 * MIB, f"unlimited: RSS grew between voids {rss[void1] // MIB} -> {rss[void2] // MIB} MiB")
    result = {"Unlimited": brief(free), "VoidRSSMiB": [rss[void1] // MIB, rss[void2] // MIB], "VoidGPUMiB": [gpu[void1] // MIB, gpu[void2] // MIB],
              "LapPeakGPUMiB": [max(gpu[:lap]) // MIB, max(gpu[lap:]) // MIB], "LapPeakRSSMiB": [max(rss[:lap]) // MIB, max(rss[lap:]) // MIB]}
    # ---- tracked GPU limit: halfway between the least and the most the unlimited run asked for (the void keeps
    # its texture cache, so it is not the floor). Never reached, and the world still streams.
    limit = (min(gpu) + max(gpu)) // 2
    limited_project = run.generate("heavy-gpu", *HEAVY)
    set_policy(limited_project, RequestedGPULimitBytes=limit)
    limited = run.tour("gpu-limit", limited_project)
    samples = column(limited, "RequestedGPUBytes")
    check(max(samples) < limit, f"gpu-limit: tracked GPU {max(samples)} reached the limit {limit}")
    check(limited["World"]["ResidencyRefusals"] + limited["World"]["PressureEvictions"] + limited["World"]["CacheEvictions"] > 0 and max(gpu) > limit,
          f"gpu-limit: the limit was never binding {brief(limited)}")
    check(limited["World"]["ResidencyRefusals"] > 0 or limited["Summary"]["PeakRequestedGPUBytes"] < max(gpu), f"gpu-limit: nothing was held back {brief(limited)}")
    check(limited["World"]["Failed"] == 0 and limited["Summary"]["PeakActive"] >= 3 and column(limited, "Active")[-1] >= 1, f"gpu-limit: {brief(limited)}")
    check(limited["World"]["MainThreadImageDecodes"] == 0 and limited["World"]["MainThreadModelParses"] == 0 and limited["World"]["OversizeUploads"] == 0,
          f"gpu-limit: main-thread loads {brief(limited)}")
    result.update(GPULimit=brief(limited), GPULimitMiB=limit // MIB)
    # ---- RSS limit: halfway between the empty world and the unlimited peak. Observed, so it is enforced after the
    # fact: frees are handed back to the system and far cells evicted until a fresh sample is under the low watermark.
    floor, peak = min(rss), max(rss)
    rss_limit = floor + (peak - floor) // 2
    rss_project = run.generate("heavy-rss", *HEAVY)
    policy = set_policy(rss_project, ObservedRSSLimitBytes=rss_limit)
    limited = run.tour("rss-limit", rss_project)
    samples, pressure = column(limited, "RSSBytes"), column(limited, "Pressure")
    result.update(RSSLimit=brief(limited), RSSLimitMiB=rss_limit // MIB, RSSOvershootMiB=max(0, max(samples) - rss_limit) // MIB,
                  RSSFramesOverLimit=sum(1 for value in samples if value > rss_limit))
    check(limited["World"]["Failed"] == 0 and limited["World"]["MainThreadImageDecodes"] == 0 and limited["World"]["MainThreadModelParses"] == 0,
          f"rss-limit: main-thread loads {brief(limited)}")
    check(sum(pressure) > 0 and limited["World"]["PressureEvictions"] + limited["World"]["MemoryReleases"] > 0, f"rss-limit: never binding {brief(limited)}")
    # What can still arrive after the limit is crossed: the cell being staged and its uploads.
    check(max(samples) <= rss_limit + policy["MaxAssetBytesPerCell"] + 64 * MIB, f"rss-limit: RSS {max(samples) // MIB} MiB over the limit {rss_limit // MIB} MiB")
    check(not pressure[-1] or samples[-1] <= rss_limit + 64 * MIB, "rss-limit: still far over the limit at the end")
    check(limited["Summary"]["PeakActive"] >= 2, f"rss-limit: the world emptied {brief(limited)}")
    # ---- damaged world: a missing cell, a corrupt cell, a corrupt and a missing texture, a corrupt model.
    damaged = run.generate("damaged", "--texture-size", "256", "--window", "640x360")
    assets = damaged / "Assets"
    (assets / "Scenes/Cells/Cell_1_0.zscene").unlink()
    (assets / "Scenes/Cells/Cell_2_0.zscene").write_text('{"Scene": "broken", "Version": 5, "Entities": [ {"Entity": 1, ')
    (assets / "Textures/Ground_3_0.png").write_bytes(b"\x89PNG\r\n\x1a\n" + b"garbage" * 40)
    (assets / "Textures/Ground_0_1.png").unlink()
    (assets / "Models/Monument_4.obj").write_text("not a model\n")
    broken = run.tour("damaged", damaged)
    world, summary = broken["World"], broken["Summary"]
    check(summary["PeakFailed"] == 2, f"damaged: {summary['PeakFailed']} failed cells at once, expected the missing and the corrupt one")
    check(world["FilesUnreadable"] >= 3 and world["Activations"] > 0 and summary["PeakActive"] >= 4, f"damaged: {brief(broken)}")
    check(world["MainThreadImageDecodes"] == 0 and world["MainThreadModelParses"] == 0 and world["OversizeUploads"] == 0, f"damaged: {brief(broken)}")
    check(column(broken, "Active")[-1] >= 1, "damaged: nothing active after the return")
    for name in ("Ground_3_0.png", "Ground_0_1.png", "Monument_4.obj"):
        check(name in broken["Log"], f"damaged: {name} was not reported")
    result.update(Damaged=brief(broken))
    return result


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def stage_demo(run):
    source = ROOT / "Projects/WorldGallery3D"
    # ---- the committed demo is exactly what the generator writes (the .zmeta UUIDs are the editor's and kept).
    fresh = run.generate("regenerated")
    files = sorted(path.relative_to(fresh) for path in fresh.rglob("*") if path.is_file())
    check(len(files) >= 70, f"demo: only {len(files)} generated files")
    for file in files:
        if file.name == "Thumbnail.png":
            continue  # the project's own picture may be replaced by a screenshot
        check((source / file).is_file() and digest(source / file) == digest(fresh / file), f"demo: {file} differs from the generator's output")
    committed = sorted(path.relative_to(source) for path in source.rglob("*") if path.is_file() and path.suffix != ".zmeta" and ".zamin" not in path.parts)
    extra = [str(path) for path in committed if path not in files and path.name != "README.md"]
    check(not extra, f"demo: files the generator does not write: {extra}")
    project = run.work / "WorldGallery3D"
    shutil.copytree(source, project, ignore=shutil.ignore_patterns("Build", "Binaries", ".zamin"))
    # ---- two runs of the tour: the same camera in every frame, the same cells at every settled point.
    first = run.tour("demo-1", project, screenshot=True)
    second = run.tour("demo-2", project)
    for report, label in ((first, "demo-1"), (second, "demo-2")):
        world = report["World"]
        check(world["Failed"] == 0 and world["FilesUnreadable"] == 0 and world["MainThreadImageDecodes"] == 0 and world["MainThreadModelParses"] == 0, f"{label}: {brief(report)}")
        check(world["OversizeUploads"] == 0 and report["Summary"]["PeakUploadBytesPerFrame"] <= report["Policy"]["MaxAssetUploadBytesPerFrame"], f"{label}: upload budget")
        check(report["Summary"]["PeakActive"] >= 6 and world["Activations"] >= 20 and world["Unloads"] >= 10, f"{label}: {brief(report)}")
        check(max(stream_ms(report)) <= HARD_STREAM_MS, f"{label}: {max(stream_ms(report)):.2f} ms of streaming work in one frame")
    camera = lambda report: [row[-3:] for row in report["Samples"]]
    check(camera(first) == camera(second), "demo: the two runs did not put the camera in the same places")
    # Settled points: the end of each slow leg, the void, and the end of the return.
    settled = [239, 419, 659, 919, 1079]
    a, b = column(first, "Active"), column(second, "Active")
    check([a[i] for i in settled] == [b[i] for i in settled] and a[919] == 0 and a[1079] > 0, f"demo: settled cells {[a[i] for i in settled]} / {[b[i] for i in settled]}")
    result = {"Run1": brief(first), "Run2": brief(second), "SettledFrames": settled, "SettledActive": [a[i] for i in settled]}
    # ---- the editor: opens the project, plays it and shows the world panel with the asset and limit counters.
    editor_log = run.out / "editor.log"
    with editor_log.open("w") as stream:
        code = subprocess.run(run.xvfb + [str(run.build / "bin/ZaminEditor"), str(project)], stdout=stream, stderr=subprocess.STDOUT, timeout=300,
                              env=run.env(ZAMIN_EDITOR_WORLD=1, ZAMIN_EDITOR_PLAY=1, ZAMIN_MAX_FRAMES=260, ZAMIN_SCREENSHOT=run.out / "editor-world.png")).returncode
    check(code == 0 and (run.out / "editor-world.png").is_file() and "GL_INVALID_" not in editor_log.read_text(errors="replace"), "demo: editor world panel run failed")
    # ---- export, then the same tour in the export after it was moved.
    export = run.work / "export"
    with (run.out / "export.log").open("w") as stream:
        code = subprocess.run(run.xvfb + [str(run.build / "bin/ZaminEditor"), str(project)], stdout=stream, stderr=subprocess.STDOUT, timeout=600,
                              env=run.env(ZAMIN_EDITOR_EXPORT=export, ZAMIN_MAX_FRAMES=8)).returncode
    report_file = export / "export-report.json"
    check(code == 0 and report_file.is_file() and json.loads(report_file.read_text()).get("Succeeded") is True, f"demo: export failed; see {run.out / 'export.log'}")
    moved = run.work / "moved elsewhere" / "Gallery"
    moved.parent.mkdir(parents=True)
    shutil.move(str(export), str(moved))
    shutil.rmtree(project)  # the export must not lean on the project it came from
    tour_copy = run.work / "Gallery.ztour"
    shutil.copy2(source / "Assets/Worlds/Gallery.ztour", tour_copy)
    exported = run.tour("exported", moved, tour=tour_copy, command=[str(moved / "WorldGallery3D.sh"), "--windowed", "--resolution", "1280x720"], screenshot=True)
    world = exported["World"]
    check(world["Failed"] == 0 and world["FilesUnreadable"] == 0 and world["MainThreadImageDecodes"] == 0 and world["Cells"] == 24, f"exported: {brief(exported)}")
    check(camera(exported) == camera(first), "exported: camera path differs from the project run")
    c = column(exported, "Active")
    check([c[i] for i in settled] == [a[i] for i in settled], f"exported: settled cells {[c[i] for i in settled]}")
    result.update(Exported=brief(exported), ExportFiles=sum(1 for path in moved.rglob("*") if path.is_file()),
                  ExportBytes=sum(path.stat().st_size for path in moved.rglob("*") if path.is_file()))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", type=Path, default=ROOT / "build")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--stage", choices=("budget", "residency", "demo"), required=True)
    parser.add_argument("--keep", type=Path, help="work in this folder and keep it (default: a temporary folder)")
    args = parser.parse_args()
    build = args.build.resolve()
    out = (args.out or build / "WorldAssetStreaming" / args.stage).resolve()
    out.mkdir(parents=True, exist_ok=True)
    stage = {"budget": stage_budget, "residency": stage_residency, "demo": stage_demo}[args.stage]
    with tempfile.TemporaryDirectory(prefix="zamin-world-assets-") as scratch:
        work = args.keep.resolve() if args.keep else Path(scratch)
        work.mkdir(parents=True, exist_ok=True)
        try:
            result = stage(Runner(build, out, work))
        except Failure as failure:
            print(f"FAIL world asset streaming ({args.stage}): {failure}", flush=True)
            return 1
    (out / "report.json").write_text(json.dumps(result, indent=2) + "\n")
    print(f"PASS world asset streaming ({args.stage}): {json.dumps(result)}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
